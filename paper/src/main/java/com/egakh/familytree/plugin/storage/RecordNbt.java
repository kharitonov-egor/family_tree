package com.egakh.familytree.plugin.storage;

import com.egakh.familytree.data.AnimalRecord;
import com.egakh.familytree.data.HorseStats;

import java.util.List;
import java.util.Set;
import java.util.UUID;

/**
 * Reads and writes records with the field names and tag types of the mod's {@code AnimalRecord.CODEC} under
 * {@code NbtOps}. Fields this version doesn't know stay in the compound, so an older plugin keeps a newer mod's data.
 */
public final class RecordNbt {
    static final Set<String> KNOWN = Set.of("id", "species", "name", "name_auto", "parent_a", "parent_b",
            "birth_world_day", "birth_epoch", "deceased", "death_world_day", "death_epoch", "owner", "owner_name",
            "variant_id", "last_seen", "death_cause", "tree_name", "horse_stats", "variant_origin");

    private RecordNbt() {}

    public static final class InvalidRecord extends Exception {
        InvalidRecord(String message) { super(message, null, false, false); }
    }

    public static AnimalRecord decode(Object tag) throws InvalidRecord {
        if (!(tag instanceof Nbt.Compound c)) throw new InvalidRecord("Record is not a compound");
        AnimalRecord record = new AnimalRecord(
                uuid(c, "id", true), string(c, "species", true), string(c, "name", true),
                bool(c, "name_auto"),
                uuid(c, "parent_a", false), uuid(c, "parent_b", false),
                number(c, "birth_world_day", true).longValue(), number(c, "birth_epoch", true).longValue(),
                bool(c, "deceased"),
                longOrNull(c, "death_world_day"), longOrNull(c, "death_epoch"),
                uuid(c, "owner", false), string(c, "owner_name", false), string(c, "variant_id", false),
                lastSeen(c.get("last_seen")), deathCause(c.get("death_cause")));
        record.setTreeName(string(c, "tree_name", false));
        record.setHorseStats(horseStats(c.get("horse_stats")));
        record.setVariantOrigin(string(c, "variant_origin", false));
        return record;
    }

    /** {@code original} is the compound the record was read from, or null for a new record. */
    public static Nbt.Compound encode(AnimalRecord record, Nbt.Compound original) {
        Nbt.Compound c = original == null ? new Nbt.Compound() : original.copy();
        for (String key : KNOWN) c.remove(key);
        c.put("id", uuid(record.id()));
        c.put("species", record.speciesId());
        c.put("name", record.originalName());
        if (record.nameAutogenerated()) c.put("name_auto", (byte) 1);
        putUuid(c, "parent_a", record.parentA());
        putUuid(c, "parent_b", record.parentB());
        c.put("birth_world_day", record.birthWorldDay());
        c.put("birth_epoch", record.birthEpochMillis());
        if (record.deceased()) c.put("deceased", (byte) 1);
        if (record.deathWorldDay() != null) c.put("death_world_day", record.deathWorldDay());
        if (record.deathEpochMillis() != null) c.put("death_epoch", record.deathEpochMillis());
        putUuid(c, "owner", record.ownerId());
        if (record.ownerName() != null) c.put("owner_name", record.ownerName());
        if (record.variantId() != null) c.put("variant_id", record.variantId());
        AnimalRecord.LastSeen seen = record.lastSeen();
        if (seen != null) {
            Nbt.Compound tag = nested(original, "last_seen", Set.of("x", "y", "z", "dimension", "world_day"));
            tag.put("x", seen.x());
            tag.put("y", seen.y());
            tag.put("z", seen.z());
            tag.put("dimension", seen.dimension());
            tag.put("world_day", seen.worldDay());
            c.put("last_seen", tag);
        }
        AnimalRecord.DeathCause cause = record.deathCause();
        if (cause != null) {
            Nbt.Compound tag = nested(original, "death_cause", Set.of("attacker", "msg_id"));
            if (cause.attacker() != null) tag.put("attacker", cause.attacker());
            if (cause.msgId() != null) tag.put("msg_id", cause.msgId());
            c.put("death_cause", tag);
        }
        if (record.treeName() != null) c.put("tree_name", record.treeName());
        HorseStats stats = record.horseStats();
        if (stats != null) {
            Nbt.Compound tag = nested(original, "horse_stats", Set.of("speed", "jump_strength", "max_health", "strength"));
            if (stats.speed() != null) tag.put("speed", stats.speed());
            if (stats.jumpStrength() != null) tag.put("jump_strength", stats.jumpStrength());
            if (stats.maxHealth() != null) tag.put("max_health", stats.maxHealth());
            if (stats.strength() != null) tag.put("strength", stats.strength());
            c.put("horse_stats", tag);
        }
        if (record.variantOrigin() != null) c.put("variant_origin", record.variantOrigin());
        return c;
    }

    public static int[] uuid(UUID id) {
        long most = id.getMostSignificantBits(), least = id.getLeastSignificantBits();
        return new int[]{(int) (most >> 32), (int) most, (int) (least >> 32), (int) least};
    }

    private static Nbt.Compound nested(Nbt.Compound original, String key, Set<String> known) {
        Object previous = original == null ? null : original.get(key);
        Nbt.Compound tag = previous instanceof Nbt.Compound compound ? compound.copy() : new Nbt.Compound();
        for (String field : known) tag.remove(field);
        return tag;
    }

    private static void putUuid(Nbt.Compound c, String key, UUID id) {
        if (id != null) c.put(key, uuid(id));
    }

    private static AnimalRecord.LastSeen lastSeen(Object tag) throws InvalidRecord {
        if (tag == null) return null;
        if (!(tag instanceof Nbt.Compound c)) throw new InvalidRecord("last_seen is not a compound");
        return new AnimalRecord.LastSeen(number(c, "x", true).doubleValue(), number(c, "y", true).doubleValue(),
                number(c, "z", true).doubleValue(), string(c, "dimension", true), number(c, "world_day", true).longValue());
    }

    private static AnimalRecord.DeathCause deathCause(Object tag) throws InvalidRecord {
        if (tag == null) return null;
        if (!(tag instanceof Nbt.Compound c)) throw new InvalidRecord("death_cause is not a compound");
        return new AnimalRecord.DeathCause(string(c, "attacker", false), string(c, "msg_id", false));
    }

    private static HorseStats horseStats(Object tag) throws InvalidRecord {
        if (tag == null) return null;
        if (!(tag instanceof Nbt.Compound c)) throw new InvalidRecord("horse_stats is not a compound");
        Number strength = number(c, "strength", false);
        return new HorseStats(doubleOrNull(c, "speed"), doubleOrNull(c, "jump_strength"), doubleOrNull(c, "max_health"),
                strength == null ? null : strength.intValue());
    }

    private static String string(Nbt.Compound c, String key, boolean required) throws InvalidRecord {
        Object value = c.get(key);
        if (value == null) {
            if (required) throw new InvalidRecord("Missing " + key);
            return null;
        }
        if (!(value instanceof String s)) throw new InvalidRecord(key + " is not a string");
        return s;
    }

    private static Number number(Nbt.Compound c, String key, boolean required) throws InvalidRecord {
        Object value = c.get(key);
        if (value == null) {
            if (required) throw new InvalidRecord("Missing " + key);
            return null;
        }
        if (!(value instanceof Number n)) throw new InvalidRecord(key + " is not a number");
        return n;
    }

    private static Long longOrNull(Nbt.Compound c, String key) throws InvalidRecord {
        Number value = number(c, key, false);
        return value == null ? null : value.longValue();
    }

    private static Double doubleOrNull(Nbt.Compound c, String key) throws InvalidRecord {
        Number value = number(c, key, false);
        return value == null ? null : value.doubleValue();
    }

    private static boolean bool(Nbt.Compound c, String key) throws InvalidRecord {
        Number value = number(c, key, false);
        return value != null && value.byteValue() != 0;
    }

    private static UUID uuid(Nbt.Compound c, String key, boolean required) throws InvalidRecord {
        Object value = c.get(key);
        if (value == null) {
            if (required) throw new InvalidRecord("Missing " + key);
            return null;
        }
        int[] ints;
        if (value instanceof int[] array) ints = array;
        else if (value instanceof Nbt.ListTag list && list.values().stream().allMatch(Number.class::isInstance)) {
            List<Object> values = list.values();
            ints = new int[values.size()];
            for (int i = 0; i < ints.length; i++) ints[i] = ((Number) values.get(i)).intValue();
        } else throw new InvalidRecord(key + " is not a UUID");
        if (ints.length != 4) throw new InvalidRecord(key + " has " + ints.length + " parts, not 4");
        return new UUID((long) ints[0] << 32 | ints[1] & 0xFFFFFFFFL, (long) ints[2] << 32 | ints[3] & 0xFFFFFFFFL);
    }
}
