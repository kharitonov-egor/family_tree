package com.egakh.familytree.data;

import com.egakh.familytree.util.AnimalCategory;

import java.util.Collection;
import java.util.Comparator;
import java.util.HashSet;
import java.util.List;
import java.util.Set;
import java.util.UUID;

/** Unnamed animals other than pets are the only records the farm limit counts and cleanup may remove. */
public final class FarmRecords {
    private FarmRecords() {}

    public static boolean unnamedFarm(AnimalRecord record) {
        return record.nameAutogenerated() && record.treeName() == null && AnimalCategory.knownNonPet(record.speciesId());
    }

    public static int count(Collection<AnimalRecord> records) {
        int count = 0;
        for (AnimalRecord record : records) if (unnamedFarm(record)) count++;
        return count;
    }

    /** Cleanup keeps three quarters of the limit, so it runs once per many births rather than on every one. */
    public static int cleanupTarget(int limit) {
        return limit * 3 / 4;
    }

    /**
     * Deceased unnamed farm records, safest to remove first: animals without recorded children,
     * then parents, each oldest death first. Pets, named animals, and living animals never appear.
     */
    public static List<AnimalRecord> removable(Collection<AnimalRecord> records) {
        Set<UUID> parents = new HashSet<>();
        for (AnimalRecord record : records) {
            if (record.parentA() != null) parents.add(record.parentA());
            if (record.parentB() != null) parents.add(record.parentB());
        }
        return records.stream()
                .filter(record -> record.deceased() && unnamedFarm(record))
                .sorted(Comparator.comparing((AnimalRecord record) -> parents.contains(record.id()))
                        .thenComparing(record -> record.deathWorldDay() == null ? Long.MIN_VALUE : record.deathWorldDay())
                        .thenComparing(record -> record.deathEpochMillis() == null ? Long.MIN_VALUE : record.deathEpochMillis())
                        .thenComparing(AnimalRecord::id))
                .toList();
    }
}
