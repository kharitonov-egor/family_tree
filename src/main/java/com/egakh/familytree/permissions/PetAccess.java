package com.egakh.familytree.permissions;

import com.egakh.familytree.data.AnimalRecord;
import java.util.Collection;
import java.util.Comparator;
import java.util.List;
import java.util.UUID;

/** Public tree viewing never grants location or editing access. */
public final class PetAccess {
    private PetAccess() {}

    public static boolean canView(AnimalRecord pet, UUID player, boolean viewAll) {
        return pet != null && (viewAll || owns(pet, player));
    }

    public static boolean canManage(AnimalRecord pet, UUID player, boolean operator) {
        return pet != null && (operator || owns(pet, player));
    }

    private static boolean owns(AnimalRecord pet, UUID player) {
        return player != null && player.equals(pet.ownerId());
    }

    /**
     * The copy a viewer receives. The last known position stays only for a pet the viewer may manage and when the
     * viewer may locate, so {@code ownersCanLocate=false} or a denied {@code familytree.locate} also hides it.
     */
    public static AnimalRecord forViewer(AnimalRecord pet, UUID player, boolean operator, boolean mayLocate) {
        AnimalRecord publicPet = new AnimalRecord(pet.id(), pet.speciesId(), pet.originalName(), pet.nameAutogenerated(),
                pet.parentA(), pet.parentB(), pet.birthWorldDay(), pet.birthEpochMillis(), pet.deceased(),
                pet.deathWorldDay(), pet.deathEpochMillis(), pet.ownerId(), pet.ownerName(), pet.variantId(),
                mayLocate && canManage(pet, player, operator) ? pet.lastSeen() : null, pet.deathCause());
        publicPet.setTreeName(pet.treeName());
        publicPet.setHorseStats(pet.horseStats());
        publicPet.setVariantOrigin(pet.variantOrigin());
        return publicPet;
    }

    /** The records a family snapshot sends, in ID order, cut at {@code limit} so the caller can detect an oversized family. */
    public static List<AnimalRecord> snapshot(Collection<AnimalRecord> records, UUID viewer, boolean viewingAll,
                                              boolean operator, boolean mayLocate, long limit) {
        return records.stream()
                .filter(record -> canView(record, viewer, viewingAll))
                .sorted(Comparator.comparing(AnimalRecord::id))
                .limit(limit)
                .map(record -> forViewer(record, viewer, operator, mayLocate)).toList();
    }
}
